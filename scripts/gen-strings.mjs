// Generates the app's string resources from i18n/: English (the default) into res/values/strings.xml from app-strings.json, and Spanish
// into res/values-es/strings.xml from app-strings.es.json. Android shows Spanish when the phone is in Spanish, English otherwise.
// Every translation must have exactly the English keys and keep each string's placeholders (%1$s, %2$d, %%); otherwise nothing is written.
// Usage: node scripts/gen-strings.mjs [--check]
// --check writes nothing and exits 1 if a committed file is stale.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// English first: it is the source every other locale is checked against.
const LOCALES = [
  { tag: "en", source: "i18n/app-strings.json", target: "app/src/main/res/values/strings.xml" },
  { tag: "es", source: "i18n/app-strings.es.json", target: "app/src/main/res/values-es/strings.xml" },
];

const BS = String.fromCharCode(92);
const esc = (s) =>
  s.split(BS).join(BS + BS)
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/'/g, BS + "'").replace(/"/g, BS + '"')
    .replace(/^([@?])/, BS + "$1");

// The format tokens of a string, order-independent: positional arguments (%1$s) and literal %%.
const placeholders = (s) => (s.match(/%(\d+\$)?[a-zA-Z%]/g) ?? []).sort().join(" ");

const fail = (msg) => {
  console.error(msg);
  process.exit(2);
};

const load = (l) => JSON.parse(fs.readFileSync(path.join(root, l.source), "utf8")).strings;
const english = load(LOCALES[0]);

const outputs = LOCALES.map((l) => {
  const strings = load(l);
  // Placeholders must be positional printf arguments (%1$s), not {name}.
  const named = Object.keys(strings).filter((k) => /\{\w+\}/.test(strings[k]));
  if (named.length) fail(`${l.source}: placeholders are not supported (${named.join(", ")}); use %1$s.`);
  if (l !== LOCALES[0]) {
    const missing = Object.keys(english).filter((k) => !(k in strings));
    const extra = Object.keys(strings).filter((k) => !(k in english));
    if (missing.length) fail(`${l.source}: missing keys: ${missing.join(", ")}`);
    if (extra.length) fail(`${l.source}: keys not in the English source: ${extra.join(", ")}`);
    const mismatched = Object.keys(english).filter((k) => placeholders(english[k]) !== placeholders(strings[k]));
    if (mismatched.length) fail(`${l.source}: placeholders differ from English in: ${mismatched.join(", ")}`);
    const blank = Object.keys(strings).filter((k) => !strings[k].trim());
    if (blank.length) fail(`${l.source}: blank strings: ${blank.join(", ")}`);
  }
  // Every locale is written in the English key order, so the files diff line by line.
  const xml =
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/gen-strings.mjs from ${l.source}. Do not edit. -->\n<resources>\n` +
    Object.keys(english).map((k) => `    <string name="${k}">${esc(strings[k])}</string>`).join("\n") + `\n</resources>\n`;
  return { ...l, xml, count: Object.keys(strings).length };
});

if (process.argv.includes("--check")) {
  // Windows checkouts may turn LF into CRLF; the content is what matters.
  const stale = outputs.filter((o) => {
    const file = path.join(root, o.target);
    return !fs.existsSync(file) || fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") !== o.xml;
  });
  for (const o of stale) console.error(`stale: ${o.target}`);
  process.exit(stale.length ? 1 : 0);
}
for (const o of outputs) {
  const file = path.join(root, o.target);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, o.xml);
  console.log(`${o.tag}: ${o.count} strings → ${o.target}`);
}
